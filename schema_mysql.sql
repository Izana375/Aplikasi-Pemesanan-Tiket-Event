CREATE DATABASE IF NOT EXISTS db_tiket_event;
USE db_tiket_event;
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(80) UNIQUE NOT NULL,
 password VARCHAR(64) NOT NULL, role VARCHAR(30) DEFAULT 'Admin'
);
CREATE TABLE IF NOT EXISTS events (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(180) NOT NULL, venue VARCHAR(180),
 event_date DATE, description TEXT
);
CREATE TABLE IF NOT EXISTS categories (
 id INT AUTO_INCREMENT PRIMARY KEY, event_id INT NOT NULL, name VARCHAR(100),
 price DECIMAL(14,2) NOT NULL DEFAULT 0, quota INT NOT NULL DEFAULT 0,
 FOREIGN KEY(event_id) REFERENCES events(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS orders (
 id INT AUTO_INCREMENT PRIMARY KEY, code VARCHAR(40) UNIQUE NOT NULL,
 customer VARCHAR(150), phone VARCHAR(40), event_id INT, category_id INT,
 qty INT NOT NULL, total DECIMAL(14,2) NOT NULL, order_date DATETIME,
 FOREIGN KEY(event_id) REFERENCES events(id), FOREIGN KEY(category_id) REFERENCES categories(id)
);
CREATE TABLE IF NOT EXISTS payments (
 id INT AUTO_INCREMENT PRIMARY KEY, order_id INT NOT NULL, method VARCHAR(50),
 status VARCHAR(30), paid_at DATETIME, FOREIGN KEY(order_id) REFERENCES orders(id)
);
